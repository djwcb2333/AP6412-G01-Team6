using Godot;
using System;
using System.Linq;
using System.Reflection;
using System.Threading.Tasks;

// Compiled only in the temporary test copy, never in the production game.
public partial class SurvivalSmokeTest : Node
{
	private const BindingFlags PrivateInstance = BindingFlags.Instance | BindingFlags.NonPublic;
	private int _checks;

	public override async void _Ready()
	{
		try
		{
			await CheckFullRound();
			await CheckDefeatAndRestart();
			GD.Print($"PASS: {_checks} Godot integration checks");
			GetTree().Quit(0);
		}
		catch (Exception error)
		{
			GD.PrintErr($"FAIL: {error}");
			GetTree().Quit(1);
		}
	}

	private async Task<Game3D> CreateGame()
	{
		Game3D game = GD.Load<PackedScene>("res://Scenes3D/Main3D.tscn").Instantiate<Game3D>();
		// Use real nodes and signals, but advance the round clock deterministically.
		game.ProcessMode = ProcessModeEnum.Disabled;
		AddChild(game);
		await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
		return game;
	}

	private async Task CheckFullRound()
	{
		Game3D game = await CreateGame();
		Node3D entities = game.GetNode<Node3D>("Entities");
		Player3D player = game.GetNode<Player3D>("Player");
		Check(EnemyCount(entities) == 0, "Opening delay has no immediate enemy");
		game._PhysicsProcess(1.5);
		Check(EnemyCount(entities) == 1, "First enemy at 1.5 seconds");
		Enemy3D first = entities.GetChildren().OfType<Enemy3D>().Single();
		Check(first is ChaserEnemy3D && first.Health == 38f, "Real Chaser scene configured");
		Check(Math.Abs(first.GlobalPosition.Y - 0.5f) < 0.001f
			&& (Math.Abs(Math.Abs(first.GlobalPosition.X) - 8.5f) < 0.001f
				|| Math.Abs(Math.Abs(first.GlobalPosition.Z) - 5.5f) < 0.001f), "Enemy on arena edge");

		// Actual enemy damage/death signals exercise scoring and kill-based type unlock.
		for (int i = 0; i < 10; i++)
		{
			if (i > 0)
			{
				Call(game, "SpawnEnemy");
			}
			Enemy3D enemy = entities.GetChildren().OfType<Enemy3D>()
				.Single(e => !e.IsQueuedForDeletion());
			Check(i < 4 ? enemy is ChaserEnemy3D : enemy is StrikerEnemy3D,
				$"Enemy type at kill {i}");
			enemy.TakeDamage(10000f);
			await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
		}
		Check(Field<int>(game, "_kills") == 10 && Field<int>(game, "_score") == 1480,
			"Ten actual kills and score recorded");
		Check(Field<bool>(game, "_running") && player.Active,
			"Ten kills do not end the survival round");

		game._PhysicsProcess(2.5);
		Check(EnemyCount(entities) == 1, "Spawning continues after ten kills");
		Check(entities.GetChildren().OfType<Enemy3D>().Single() is StrikerEnemy3D,
			"Unlocked Striker generated by scheduler");
		game._PhysicsProcess(15.75); // 19.75 seconds elapsed: 8 scheduled spawns so far.
		Check(EnemyCount(entities) == 7, "Eight scheduled spawns in first stage");
		game._PhysicsProcess(20.0); // 39.75 seconds elapsed.
		Check(EnemyCount(entities) == 18, "Eleven additional scheduled spawns in second stage");
		game._PhysicsProcess(20.0); // 59.75 seconds elapsed.
		Check(EnemyCount(entities) == 38, "Twenty additional scheduled spawns in final stage");
		game._PhysicsProcess(0.25);
		Check(!Field<bool>(game, "_running") && !player.Active,
			"Existing sixty-second victory stops round and player");
		int finalCount = EnemyCount(entities);
		game._PhysicsProcess(10.0);
		Check(EnemyCount(entities) == finalCount, "No enemies after victory");
		game.QueueFree();
		await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
	}

	private async Task CheckDefeatAndRestart()
	{
		Game3D game = await CreateGame();
		Node3D entities = game.GetNode<Node3D>("Entities");
		Player3D player = game.GetNode<Player3D>("Player");
		game._PhysicsProcess(21.5);
		Check(EnemyCount(entities) == 9, "Low-frequency update catches up due enemies");
		player.TakeDamage(10000f);
		Check(!Field<bool>(game, "_running") && !player.Active && player.Health == 0f,
			"Actual death signal ends round early");
		int defeatCount = EnemyCount(entities);
		game._PhysicsProcess(60.0);
		Check(EnemyCount(entities) == defeatCount, "No enemies after defeat");

		Call(game, "StartGame");
		await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
		Check(EnemyCount(entities) == 0 && player.Health == 100f && player.Active,
			"Restart clears enemies and resets player");
		Check(Field<float>(game, "_remainingTime") == 60f && Field<int>(game, "_kills") == 0,
			"Restart resets teammate timer and score progression");
		game._PhysicsProcess(1.0);
		Check(EnemyCount(entities) == 0, "Restart restores opening delay");
		game._PhysicsProcess(0.5);
		Check(EnemyCount(entities) == 1, "Restart first enemy at 1.5 seconds");
		game._PhysicsProcess(2.5);
		Check(EnemyCount(entities) == 2, "Restart restores easy interval");

		Call(game, "StartGame");
		await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
		game._PhysicsProcess(60.0);
		Check(EnemyCount(entities) == 0 && !Field<bool>(game, "_running"),
			"Terminal tick has priority over overdue spawns");
		game.QueueFree();
		await ToSignal(GetTree(), SceneTree.SignalName.ProcessFrame);
	}

	private static int EnemyCount(Node3D entities) => entities.GetChildren().OfType<Enemy3D>()
		.Count(e => !e.IsQueuedForDeletion());

	private static T Field<T>(Game3D game, string name) =>
		(T)typeof(Game3D).GetField(name, PrivateInstance)!.GetValue(game)!;

	private static void Call(Game3D game, string name) =>
		typeof(Game3D).GetMethod(name, PrivateInstance)!.Invoke(game, null);

	private void Check(bool condition, string message)
	{
		if (!condition)
		{
			throw new InvalidOperationException(message);
		}
		_checks++;
	}
}
